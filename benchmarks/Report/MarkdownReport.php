declare(strict_types=1);

namespace Lisachenko\Generics\Benchmark\Report;

use Lisachenko\Generics\Benchmark\Scenario\ScenarioReport;

/**
 * Renders finished scenarios as the committed `docs/benchmarks.md`
 *
 * The document is generated rather than written so that nobody has to remember to update a
 * number, and so that a number in it can always be reproduced by re-running the command
 * printed at the top of it.
 */
final class MarkdownReport
{
    /**
     * @param list<ScenarioReport> $reports
     */
    public function render(array $reports, bool $smoke): string
    {
        $lines = [
            '# Benchmarks',
            '',
            'Generated by `composer bench`. Do not edit by hand - re-run the command.',
            '',
        ];

        if ($smoke) {
            $lines[] = '> **Smoke run.** These numbers come from the tiny grid CI uses to prove the';
            $lines[] = '> harness still runs. They are not a measurement; run `composer bench` for that.';
            $lines[] = '';
        }

        $lines[] = 'The question underneath all of this is the one the compile-time generics';
        $lines[] = 'discussions keep stalling on: **monomorphization is assumed to cost a copy of the';
        $lines[] = 'code per instantiation.** Here it does not, because the specialized class entry';
        $lines[] = 'shares its method bodies with the template, and these tables are the evidence.';
        $lines[] = '';

        $lines = [...$lines, ...$this->environment()];

        foreach ($reports as $report) {
            $lines = [...$lines, ...$this->scenario($report)];
        }

        return implode("\n", $lines) . "\n";
    }

    /**
     * @return list<string>
     */
    private function environment(): array
    {
        $lines = ['## Environment', ''];
        foreach ([...SystemInfo::collect(), ...$this->structSizes()] as $key => $value) {
            $lines[] = sprintf('- **%s** — %s', $key, $value);
        }
        $lines[] = '';
        $lines[] = 'Struct sizes are read from the running engine. They are part of the result: a';
        $lines[] = 'byte count only means something next to the size of the things being counted.';
        $lines[] = '';

        return $lines;
    }

    /**
     * @return array<string, string>
     */
    private function structSizes(): array
    {
        $sizes = [];
        foreach (EngineFacts::structSizes() as $type => $size) {
            $sizes[sprintf('sizeof(%s)', $type)] = sprintf('%d bytes', $size);
        }

        return $sizes;
    }

    /**
     * @return list<string>
     */
    private function scenario(ScenarioReport $report): array
    {
        $lines = [
            sprintf('## %s', $report->title),
            '',
            sprintf('*%s*', $report->question),
            '',
            '| ' . implode(' | ', $report->columns) . ' |',
            '|' . str_repeat('---|', count($report->columns)),
        ];

        foreach ($report->rows as $row) {
            $cells = [];
            foreach ($report->columns as $column) {
                $cells[] = (string) ($row[$column] ?? '');
            }
            $lines[] = '| ' . implode(' | ', $cells) . ' |';
        }

        $lines[] = '';
        foreach ($report->findings as $finding) {
            $lines[] = sprintf('- %s', $finding);
        }
        $lines[] = '';

        return $lines;
    }
}
